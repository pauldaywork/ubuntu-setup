# Split one row. Sets REPO_PATH / HOME_PATH / KIND for the caller.
#
# A function rather than an inline IFS read at each call site, so the three
# consumers cannot disagree about the field order.
map_entry() {
    local row="$1"
    REPO_PATH="${row%%|*}"
    local rest="${row#*|}"
    HOME_PATH="${rest%%|*}"
    KIND="${rest##*|}"
}
